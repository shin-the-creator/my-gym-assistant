// (작은 모델이 지시를 놓치더라도 위험한 식단 조언이 나가지 않게 앱에서 먼저 막는다).

const RISK_PATTERNS = [
  /프로아나/,
  /거식/,
  /폭식/,
  /먹토/,
  /씹뱉/,
  /뼈\s*말라/,
  /개\s*말라/,
  /토\s*하(?:고|면|기|려|는)/,
  /억지로\s*토/,
  /구토/,
  /(?:설사약|변비약|이뇨제|식욕\s*억제제|다이어트\s*약)/,
  /(?:며칠|이틀|사흘|일주일)\s*(?:동안\s*)?(?:굶|안\s*먹)/,
];

export function hasEatingDisorderRisk(text: string): boolean {
  const t = text.replace(/\s+/g, ' ');
  return RISK_PATTERNS.some((r) => r.test(t));
}

